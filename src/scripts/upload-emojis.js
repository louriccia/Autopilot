// Keep the bot's application emojis in step with the repo. Application emojis render in every server the
// bot is in, with no membership or "Use External Emojis" requirement.
//
//   node src/scripts/upload-emojis.js            upload anything missing, then update the files below
//   node src/scripts/upload-emojis.js --list     show the application's current emojis
//   node src/scripts/upload-emojis.js --replace pal_   re-upload generated icons whose name starts with pal_
//   node src/scripts/upload-emojis.js --replace-list names.txt   re-upload the generated icons named in the file
//
// Two sources:
//   - assets/emoji/<name>.png, generated by tools/import_swgr.py (stat, part and ability icons). Uploaded
//     under <name>; every application emoji is then written to src/data/discord/app-emoji.json.
//   - server emojis written into src/data/discord/emoji.js as <:name:id>. Copied from Discord's CDN and
//     the reference rewritten to the application's copy.
//
// Safe to re-run: an emoji whose name already exists on the application is reused, not uploaded again.
// To replace icons whose image changed, use --replace with their name prefix.

require('dotenv').config({ path: __dirname + '/../../.env' })

const fs = require('node:fs');
const path = require('node:path');
const { REST, Routes } = require('discord.js');

const EMOJI_FILE = path.join(__dirname, '../data/discord/emoji.js');
const APP_EMOJI_FILE = path.join(__dirname, '../data/discord/app-emoji.json');
const ICON_DIR = path.join(__dirname, '../../assets/emoji');

const clientID = process.env.clientId;
const token = process.env.token;
if (!clientID || !token) {
    console.error('Missing clientId or token in .env - nothing to do.');
    process.exit(1);
}
const rest = new REST({ version: '10' }).setToken(token);
const format = e => `<${e.animated ? 'a' : ''}:${e.name}:${e.id}>`;

let uploaded = 0, failed = 0;
async function upload(name, image) {
    try {
        const created = await rest.post(Routes.applicationEmojis(clientID), { body: { name, image } });
        uploaded++;
        console.log(`  uploaded ${name}`);
        return created;
    } catch (err) {
        failed++;
        console.log(`  FAILED ${name}: ${err.message}`);
        return null;
    }
}

(async () => {
    const existing = (await rest.get(Routes.applicationEmojis(clientID))).items;
    if (process.argv[2] === '--list') {
        for (const e of existing) console.log(format(e));
        console.log(`${existing.length} application emoji(s)`);
        return;
    }
    const byName = new Map(existing.map(e => [e.name, e]));

    // --replace <prefix>: the importer redrew these icons, so delete the application's copies to upload them again.
    // --replace-list <file>: the same for exactly the names in the file, one per line (icons with no shared prefix,
    // like the part icons)
    if (process.argv[2]?.startsWith('--replace') && process.argv[3]) {
        const names = process.argv[2] === '--replace-list' && new Set(fs.readFileSync(process.argv[3], 'utf8').split(/\r?\n/).map(s => s.trim()).filter(Boolean))
        const matches = name => names ? names.has(name) : name.startsWith(process.argv[3])
        for (const e of existing.filter(e => matches(e.name) && fs.existsSync(path.join(ICON_DIR, `${e.name}.png`)))) {
            await rest.delete(Routes.applicationEmoji(clientID, e.id));
            byName.delete(e.name);
            console.log(`  deleted ${e.name}`);
        }
    }

    // generated icons
    for (const file of fs.existsSync(ICON_DIR) ? fs.readdirSync(ICON_DIR).filter(f => f.endsWith('.png')).sort() : []) {
        const name = path.basename(file, '.png');
        if (byName.has(name)) continue;
        const image = `data:image/png;base64,${fs.readFileSync(path.join(ICON_DIR, file)).toString('base64')}`;
        const created = await upload(name, image);
        if (created) byName.set(name, created);
    }

    // server emojis referenced in emoji.js
    let source = fs.readFileSync(EMOJI_FILE, 'utf8');
    for (const ref of new Set(source.match(/<a?:\w+:\d+>/g))) {
        const [, animated, name, id] = ref.match(/<(a?):(\w+):(\d+)>/);
        let app = byName.get(name);
        if (app?.id === id) continue;
        if (!app) {
            const ext = animated ? 'gif' : 'png';
            const res = await fetch(`https://cdn.discordapp.com/emojis/${id}.${ext}?size=128`);
            if (!res.ok) {
                failed++;
                console.log(`  FAILED ${name}: CDN answered ${res.status}`);
                continue;
            }
            app = await upload(name, `data:image/${ext};base64,${Buffer.from(await res.arrayBuffer()).toString('base64')}`);
            if (!app) continue;
            byName.set(name, app);
        }
        source = source.split(ref).join(format(app));
    }
    fs.writeFileSync(EMOJI_FILE, source);

    const all = Object.fromEntries([...byName.values()].sort((a, b) => a.name.localeCompare(b.name)).map(e => [e.name, format(e)]));
    fs.writeFileSync(APP_EMOJI_FILE, JSON.stringify(all, null, 2) + '\n');

    console.log(`${uploaded} uploaded, ${failed} failed; ${Object.keys(all).length} application emojis in app-emoji.json.`);
    if (failed) process.exitCode = 1;
})().catch(err => {
    console.error(err);
    process.exitCode = 1;
});
